/**
 * Vertical-slice sync server (dev only): the landed Postgres server (`echo-sync/server`) serving the
 * harness app (examples/browser-spike/app.ts) at `/sync`, HTTP POST + NDJSON, on Bun. See
 * AGENTS.md "Browser scenarios".
 *
 *   ECHO_PG_URL=postgres://postgres:echo@localhost:5432/postgres bun examples/server/main.ts
 *
 * At startup it creates the database `ECHO_SLICE_DB` (default `echo_slice`) if missing, then builds
 * `Startup.layer`: engine migrations, the app migrations in ./migrations, attach, `Migrate.verify`.
 * If the database drifted from the registry it prints the `Drift` (every mismatch) and exits 1
 * without listening. The reference consumer for docs/getting-started.md. Not production code:
 * the principal is read from a header the client sets (no authentication), and `/admin/*` lets the
 * scenarios grant, revoke and inspect the ledger.
 */
import * as PgClient from "@effect/sql-pg/PgClient"
import { Cause, Effect, Exit, Layer, ManagedRuntime, Redacted, Schedule, Scope } from "effect"
import * as HttpRouter from "effect/http/HttpRouter"
import { SqlClient } from "effect/sql/SqlClient"
import { AccessScope, Protocol, ScopeGrants } from "../../src/core/index.ts"
import { Postgres, Startup } from "../../src/server/index.ts"
import createTodos from "./migrations/001_create_todos.ts"
import addTodoNote from "./migrations/002_add_todo_note.ts"
import scopeWalkIndex from "./migrations/003_scope_walk_index.ts"
import { principalHeader, registry, serverHooks, serverMutations, Todos } from "../browser-spike/app.ts"

const port = Number(process.env["ECHO_SLICE_PORT"] ?? "5200")
const adminUrl = new URL(process.env["ECHO_PG_URL"] ?? "postgres://postgres:echo@localhost:5432/postgres")
const dbName = process.env["ECHO_SLICE_DB"] ?? "echo_slice"
const dbUrl = new URL(adminUrl)
dbUrl.pathname = `/${dbName}`

const ensureDatabase = Effect.gen(function* () {
  const sql = yield* SqlClient
  const found = yield* sql`SELECT 1 FROM pg_database WHERE datname = ${dbName}`
  if (found.length === 0) yield* sql.unsafe(`CREATE DATABASE "${dbName}"`)
  // oxlint-disable-next-line effecttsgo/strict-effect-provide -- Startup administrative runner owns a short-lived pool before the application database runtime exists.
}).pipe(Effect.provide(PgClient.layer({ url: Redacted.make(adminUrl.toString()), maxConnections: 1 })))

const Db = PgClient.layer({ url: Redacted.make(dbUrl.toString()), maxConnections: 40 })

/**
 * The app's migrations (SPEC §13), run by `Startup` in `echo_sync.app_migrations` after the engine's.
 * Generated by core `Migrate.generate` from the registry and committed with `migrations/manifest.json`
 * (see docs/getting-started.md).
 */
const appMigrations = {
  "001_create_todos": createTodos,
  "002_add_todo_note": addTodoNote,
  "003_scope_walk_index": scopeWalkIndex
}

/** migrate → app migrations → attach → verify, then `/sync`. On `Drift` the layer fails and nothing serves. */
const sync = Startup.layer({
  registry,
  mutations: serverMutations,
  appMigrations,
  principalFor: (headers) => {
    // HTTP-boundary policy: these are the real request headers, never NDJSON message headers.
    // Reject sibling origins too: same-site is not the same as same-origin.
    const site = headers["sec-fetch-site"]
    if (site === "cross-site" || site === "same-site") {
      return Effect.fail(
        new Protocol.Unauthorized({ reason: "authenticationRefused", message: "cross-origin sync request" })
      )
    }
    // Non-browser callers can omit Sec-Fetch-Site. Production apps must authenticate a secret
    // session cookie / bearer token here; this harness's principal header is not authentication.
    const principal = headers[principalHeader]
    return principal === undefined || principal === ""
      ? Effect.fail(
          new Protocol.Unauthorized({ reason: "authenticationRefused", message: `missing ${principalHeader}` })
        )
      : Effect.succeed(AccessScope.PrincipalId.make(principal))
  }
}).pipe(Layer.provide(Db))

// ── /admin: what the scenarios need to drive and observe the server ─────────────────────────────────
const admin = ManagedRuntime.make(Db)

/** Per client id, how many requests of each RPC tag reached this process (read from the NDJSON body). */
const rpcCounts = new Map<string, Record<string, number>>()
const countRpcs = (body: string) => {
  for (const line of body.split("\n")) {
    if (line.trim() === "") continue
    const message: unknown = JSON.parse(line)
    if (typeof message !== "object" || message === null) continue
    const tag = "tag" in message && typeof message.tag === "string" ? message.tag : undefined
    const payload = "payload" in message ? message.payload : undefined
    const clientId =
      typeof payload === "object" && payload !== null && "clientId" in payload && typeof payload.clientId === "string"
        ? payload.clientId
        : undefined
    if (tag === undefined || clientId === undefined) continue
    const counts = rpcCounts.get(clientId) ?? {}
    counts[tag] = (counts[tag] ?? 0) + 1
    rpcCounts.set(clientId, counts)
  }
}

const json = (value: unknown) =>
  new Response(
    JSON.stringify(value, (_, v: unknown) => (typeof v === "bigint" ? String(v) : v)),
    {
      headers: { "content-type": "application/json" }
    }
  )

const adminRoute = (url: URL) =>
  Effect.gen(function* () {
    const sql = yield* SqlClient
    const q = (name: string) => url.searchParams.get(name) ?? ""
    switch (url.pathname) {
      case "/admin/bootstrap-seed": {
        const count = Number(q("count"))
        if (!Number.isSafeInteger(count) || count < 1 || count > 100_000) {
          return new Response("count must be 1..100000", { status: 400 })
        }
        // Server-minted identities: no previous run's rows or grants can enter this snapshot.
        const scope = AccessScope.AccessScopeId.make(`bootstrap-${crypto.randomUUID()}`)
        const principal = AccessScope.PrincipalId.make(`bootstrap-${crypto.randomUUID()}`)
        yield* sql.withTransaction(
          Effect.gen(function* () {
            yield* sql`INSERT INTO echo_sync.access_scopes (id) VALUES (${scope})`
            yield* sql`INSERT INTO echo_sync.scope_grants (id, access_scope_id, principal_id, role, granted_at)
            VALUES (${ScopeGrants.grantId(scope, principal)}, ${scope}, ${principal}, 'reader', now())`
            yield* sql`INSERT INTO todos (id, access_scope_id, title, note)
            SELECT ${scope} || '-' || lpad(i::text, 6, '0'), ${scope}, 'Todo ' || i::text,
              CASE WHEN i % 3 = 0 THEN NULL ELSE 'Note ' || i::text || ' café' END
            FROM generate_series(1, ${count}::integer) AS g(i)`
          })
        )
        return json({ scope, principal, count })
      }
      case "/admin/grant": {
        const scope = AccessScope.AccessScopeId.make(q("scope"))
        const principal = AccessScope.PrincipalId.make(q("principal"))
        yield* sql`INSERT INTO echo_sync.access_scopes (id) VALUES (${scope}) ON CONFLICT DO NOTHING`
        yield* sql`INSERT INTO echo_sync.scope_grants (id, access_scope_id, principal_id, role, granted_at)
          VALUES (${ScopeGrants.grantId(scope, principal)}, ${scope}, ${principal}, ${q("role") || "writer"}, now())
          ON CONFLICT DO NOTHING`
        return json({ ok: true })
      }
      case "/admin/revoke":
        yield* sql`DELETE FROM echo_sync.scope_grants WHERE access_scope_id = ${q("scope")} AND principal_id = ${q("principal")}`
        return json({ ok: true })
      case "/admin/ledger":
        // Every ledger row for a mutation id, across clients: exactly-once means exactly one row.
        return json(
          yield* sql`SELECT client_id, mutation_id, seq, position, outcome FROM echo_sync.mutations
            WHERE mutation_id = ${q("mutationId")} ORDER BY position`
        )
      case "/admin/todos":
        return json(
          yield* sql.unsafe(
            `SELECT id, access_scope_id, title, note FROM ${Todos.name} WHERE access_scope_id = $1 ORDER BY id`,
            [q("scope")]
          )
        )
      case "/admin/rejections":
        serverHooks.rejecting = q("enabled") !== "0"
        return json({ rejecting: serverHooks.rejecting })
      case "/admin/open":
        return json({ wasClosed: serverHooks.open(q("gate")) })
      case "/admin/stats":
        return json({
          rpcs: rpcCounts.get(q("clientId")) ?? {},
          started: serverHooks.started.get(q("todo")) ?? 0
        })
      default:
        return new Response("not found", { status: 404 })
    }
  })

await Effect.runPromise(ensureDatabase)
// Build the sync layer before listening, so a startup failure (e.g. `Drift`, with every mismatch)
// exits the process instead of surfacing on the first request. toWebHandler reuses this build
// (and its router) through the shared MemoMap.
const memoMap = Layer.makeMemoMapUnsafe()
const startupScope = Scope.makeUnsafe()
const started = await Effect.runPromiseExit(
  Layer.buildWithMemoMap(Layer.provideMerge(sync, HttpRouter.layer), memoMap, startupScope)
)
if (Exit.isFailure(started)) {
  console.error(Cause.pretty(started.cause))
  process.exit(1)
}
const web = HttpRouter.toWebHandler(sync, { disableLogger: true, memoMap })

const server = Bun.serve({
  port,
  hostname: "127.0.0.1",
  // The pokes stream is a long-lived response that may stay quiet for minutes.
  idleTimeout: 0,
  fetch: async (request) => {
    const url = new URL(request.url)
    if (url.pathname.startsWith("/admin/")) {
      return admin.runPromise(adminRoute(url)).catch((error: unknown) => new Response(String(error), { status: 500 }))
    }
    if (url.pathname === "/sync" || url.pathname === "/sync/") countRpcs(await request.clone().text())
    return web.handler(request)
  }
})
// Ledger expiry (SPEC §11): the app's server schedules it. Hourly, default 7-day retention;
// a failed run is logged and the next one retries.
admin.runFork(
  Effect.repeat(
    Effect.catchCause(Postgres.expireLedger(), (cause) => Effect.logWarning("ledger expiry failed", cause)),
    Schedule.spaced("1 hour")
  )
)
console.log(`echo-sync slice server on http://127.0.0.1:${server.port}/sync (database ${dbName})`)

const shutdown = () => {
  void server.stop(true)
  // Each step runs even if the one before it rejects: the startup scope owns the shared build.
  void web
    .dispose()
    // oxlint-disable-next-line typescript/no-misused-promises -- finally awaits these cleanup promises in order
    .finally(() => Effect.runPromise(Scope.close(startupScope, Exit.void)))
    // oxlint-disable-next-line typescript/no-misused-promises -- finally awaits these cleanup promises in order
    .finally(() => admin.dispose())
    .finally(() => process.exit(0))
}
process.on("SIGTERM", shutdown)
process.on("SIGINT", shutdown)
